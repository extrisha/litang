/// 标准化教室名称（处理全校排课库中别名）
String normalizeClassroomName(String name) {
  return name.trim()
      .replaceAll('卓越工程大楼', '卓越楼')
      .replaceAll('第一教学楼', '一教')
      .replaceAll('第三教学楼', '三教')
      .replaceAll('第四教学楼', '四教')
      .replaceAll('综合A', '综合楼A区')
      .replaceAll('综合B', '综合楼B区')
      .replaceAll('综合C', '综合楼C区')
      .replaceAll('综合D', '综合楼D区');
}
