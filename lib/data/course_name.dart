/// 课程名归一化。
///
/// 教务（JWGL）、一网畅学（TronClass）、学习通三个系统的课程名格式各不相同，
/// 页面上「用本学期课表过滤往期课程」全靠这个函数做的字符串匹配。
/// 以前它被复制在 `LifePage` 和 `LifeTodoCard` 两份，任何一侧改动都会让
/// 待办卡片和课程卡片的过滤结果对不上，因此收敛到这里。
class CourseName {
  CourseName._();

  /// 全角括号转半角、去掉「(2026-2027-1)」这类学期后缀、压缩空白。
  ///
  /// 只去掉学期后缀，保留课程本身的 `(1)`/`(2)` —— 同名课程的不同分册
  /// 是两个不同的课，合并会让课表定位错到另一门课上。
  ///
  /// 学期段后面不一定跟内容：教务是 `高等数学（1）`，学习通/空教室接口则是
  /// `(2026-2027-1)-19101230-02`。所以尾部 `-...` 是可选的，否则
  /// 「课程名 + 裸学期后缀」这种写法根本剥不掉，两个系统的课名对不上。
  static String clean(String raw) {
    return raw
        .replaceAll('（', '(')
        .replaceAll('）', ')')
        .replaceAll(RegExp(r'\(\d{4}-\d{4}-\d\)(?:-.*)?$'), '')
        .replaceAll(RegExp(r'\s+'), '')
        .trim();
  }
}
